import { beforeEach, afterEach, expect, it } from 'vitest';
import { createTestStore, removeTestStore, readStoredResource } from '../../../backend/test-support.mjs';
import { render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter } from 'react-router-dom';
import App from '../App';
import { GitResourceStore } from '../../../backend/GitResourceStore.mjs';
import { createApi } from '../../../backend/api.mjs';
import { HttpSubscriptionService } from '~/services/subscriptions/HttpSubscriptionService';
import { configureSubscriptionService } from '~/services/subscriptions/configuredService';
let directory:string;
let store:GitResourceStore;
let service:HttpSubscriptionService;
beforeEach(async()=>{
  store=await createTestStore();directory=store.directory;
  const handle=createApi(store);
  // Exercise the real HTTP request/response contract without binding a sandbox socket.
  const transport:typeof fetch=(url,options)=>handle(new Request(new URL(String(url),'http://localhost'),options));
  service=new HttpSubscriptionService('/api',transport);configureSubscriptionService(service);
});
afterEach(async()=>{await removeTestStore(store);});
it('creates, edits and deletes through the UI and HTTP service against real Git files',async()=>{
  const user=userEvent.setup();render(<MemoryRouter initialEntries={['/subscriptions']}><App /></MemoryRouter>);
  expect(await screen.findByTestId('empty-subscriptions-page')).toBeVisible();
  await user.click(screen.getByTestId('create-subscription-button'));
  await user.type(await screen.findByTestId('subscription-name-desc-name'),'Git team');
  await user.type(screen.getByRole('combobox',{name:'Enter groups'}),'engineering');
  const group=await screen.findByRole('option',{name:'Add group "engineering"'});await user.click(group.querySelector('button') ?? group);
  await user.keyboard('{Escape}');
  await user.click(screen.getByTestId('add-models-button'));
  await user.click(screen.getByTestId('toggle-model-granite-3-8b'));
  await user.click(screen.getByTestId('confirm-add-models'));
  await user.click(screen.getByTestId('add-token-limit-0'));
  await user.click(screen.getByTestId('save-rate-limits'));
  await user.click(screen.getByTestId('create-subscription-button'));
  const link=await screen.findByRole('link',{name:'Git team'});
  const file='subscriptions/maas/git-team.json';
  let resource=await readStoredResource(directory,file);
  expect(resource.kind).toBe('MaaSSubscription');expect(resource.spec.modelRefs[0].tokenRateLimits).toEqual([{limit:1000,window:'1h'}]);
  await user.click(link);await screen.findByTestId('subscription-details-section');
  await user.click(screen.getByTestId('subscription-actions-toggle'));await user.click(screen.getByRole('menuitem',{name:'Edit'}));
  const name=await screen.findByTestId('subscription-name-desc-name');await user.clear(name);await user.type(name,'Git team updated');
  await user.click(screen.getByTestId('update-subscription-button'));
  const updatedLink=await screen.findByRole('link',{name:'Git team updated'});
  resource=await readStoredResource(directory,file);expect(resource.metadata.annotations['openshift.io/display-name']).toBe('Git team updated');
  await user.click(updatedLink);await screen.findByTestId('subscription-details-section');
  await user.click(screen.getByTestId('subscription-actions-toggle'));await user.click(screen.getByRole('menuitem',{name:'Delete'}));
  const modal=await screen.findByTestId('delete-subscription-modal');await user.type(screen.getByTestId('delete-modal-input'),'Git team updated');
  await user.click(within(modal).getByRole('button',{name:'Delete'}));
  expect(await screen.findByTestId('empty-subscriptions-page')).toBeVisible();
  await expect(readStoredResource(directory,file)).rejects.toMatchObject({code:'ENOENT'});
  await expect(readStoredResource(directory,'authorization-policies/maas/git-team-policy.json')).rejects.toMatchObject({code:'ENOENT'});
  const recreated=await service.create({...resource.spec,modelRefs:resource.spec.modelRefs.map(({name,tokenRateLimits}:{name:string;tokenRateLimits:{limit:number;window:string}[]})=>({name,tokenRateLimits})),name:'git-team',displayName:'Git team recreated',createAuthPolicy:true});
  expect(recreated.authPolicy?.name).toBe('git-team-policy');
  expect(recreated.subscription.phase).toBe('Saved');
  await expect(store.git('rev-parse','--verify','HEAD')).rejects.toThrow();
  expect(await store.git('status','--porcelain')).toContain('authorization-policies');
},15000);
it('shows a real backend conflict and keeps the unsaved form',async()=>{
  const input={name:'engineering',displayName:'Engineering',priority:1,owner:{groups:[{name:'engineering'}]},
    modelRefs:[{name:'granite-3-8b',tokenRateLimits:[{limit:1000,window:'1h'}]}],createAuthPolicy:false};
  await service.create(input);
  const user=userEvent.setup();render(<MemoryRouter initialEntries={['/subscriptions/edit/engineering']}><App /></MemoryRouter>);
  const name=await screen.findByTestId('subscription-name-desc-name');await user.clear(name);await user.type(name,'Unsaved name');
  const current=(await service.getInfo('engineering')).subscription;
  await service.update(current.name,{...input,priority:20},current.revision!);
  await user.click(screen.getByTestId('update-subscription-button'));
  expect(await screen.findByText('This subscription changed. Reload it before saving or deleting.')).toBeVisible();
  expect(name).toHaveValue('Unsaved name');
  expect((await service.getInfo('engineering')).subscription.displayName).toBe('Engineering');
});
