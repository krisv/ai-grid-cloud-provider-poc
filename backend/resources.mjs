// MaaS CR mapping follows dashboard commit 8051fbbea117457b4da4074fb2856b732e6677a4,
// packages/maas/bff/internal/repositories/subscriptions.go, and controller commit
// 83391711e701f17ddb9b212aa81e591ec1758d15, maassubscription_types.go.
import { createHash } from 'node:crypto';
const apiVersion = 'maas.opendatahub.io/v1alpha1';
const displayAnnotation = 'openshift.io/display-name';
const descriptionAnnotation = 'openshift.io/description';
const createdAnnotation = 'maas-admin.portal/created-at';
const subscriptionAnnotation = 'maas-admin.portal/subscription';
export function isSubscriptionPolicy(cr, name) {
  if(cr.kind!=='MaaSAuthPolicy' || cr.metadata.name!==`${name}-policy`)return false;
  const annotation=cr.metadata.annotations ?? {};
  if(Object.hasOwn(annotation,subscriptionAnnotation))return annotation[subscriptionAnnotation]===name;
  // Recognize policies generated by earlier versions of this PoC.
  return Boolean(annotation[createdAnnotation]) && annotation[descriptionAnnotation]===`Auth policy created for subscription "${name}"`;
}
export const serialize = value => `${JSON.stringify(value,null,2)}\n`;
export const revisionOf = content => createHash('sha256').update(content).digest('hex');
export function annotations(input, existing = {}) {
  const result = {...existing};
  for (const [field,key] of [['displayName',displayAnnotation],['description',descriptionAnnotation]]) {
    if (Object.hasOwn(input,field)) {
      if (input[field]) result[key]=input[field]; else delete result[key];
    }
  }
  return result;
}
function modelSpec(ref, previous = {}) {
  const result = {...previous,...structuredClone(ref)};
  // These are lookup presentation fields, never CR spec fields.
  for (const key of ['displayName','description','modelRef','phase','status','reason','statusMessage','endpoint']) delete result[key];
  if (result.unlimited) delete result.tokenRateLimits;
  return result;
}
export function subscriptionResource(input, namespace, existing) {
  const cr = existing ? structuredClone(existing) : {apiVersion,kind:'MaaSSubscription',metadata:{name:input.name,namespace,annotations:{[createdAnnotation]:new Date().toISOString()}},spec:{}};
  cr.metadata.annotations=annotations(input,cr.metadata.annotations);
  const oldRefs=cr.spec.modelRefs ?? [];
  cr.spec.owner={...cr.spec.owner,...structuredClone(input.owner)};
  cr.spec.modelRefs=input.modelRefs.map(ref=>modelSpec({...ref,namespace},oldRefs.find(old=>old.name===ref.name && old.namespace===namespace)));
  cr.spec.priority=input.priority;
  for (const key of ['tokenMetadata','inferencePriority','guardrails']) {
    if (Object.hasOwn(input,key) && input[key] !== undefined) cr.spec[key]=structuredClone(input[key]);
  }
  return cr;
}
export function policyResource(input, namespace) {
  return {apiVersion,kind:'MaaSAuthPolicy',metadata:{name:`${input.name}-policy`,namespace,
    annotations:{[subscriptionAnnotation]:input.name,[descriptionAnnotation]:`Auth policy created for subscription "${input.name}"`,[createdAnnotation]:new Date().toISOString()}},
    spec:{modelRefs:input.modelRefs.map(({name})=>({name,namespace})),subjects:structuredClone(input.owner),
      ...(input.tokenMetadata ? {meteringMetadata:structuredClone(input.tokenMetadata)} : {})}};
}
function presentation(cr) {
  const annotation=cr.metadata.annotations ?? {};
  return {name:cr.metadata.name,displayName:annotation[displayAnnotation],description:annotation[descriptionAnnotation],
    creationTimestamp:cr.metadata.creationTimestamp ?? annotation[createdAnnotation],deletionTimestamp:cr.metadata.deletionTimestamp,
    phase:annotation['maas-admin.portal/demo-phase'] ?? (cr.kind==='MaaSSubscription' ? 'Saved' : 'Pending'),
    statusMessage:'Saved to Git. This PoC does not apply resources or run cluster reconciliation.',
    reason:'GitOnly'};
}
export function modelDomain(cr,revision) {
  return {...presentation(cr),...(revision ? {revision} : {}),modelRef:cr.spec.modelRef,endpoint:cr.spec.endpointOverride ?? cr.status?.endpoint};
}
export function subscriptionDomain(cr, revision, models = []) {
  return {...structuredClone(cr.spec),...presentation(cr),revision,owner:{...cr.spec.owner,groups:cr.spec.owner.groups ?? []},
    modelRefs:(cr.spec.modelRefs ?? []).map(ref=>{
      const summary=models.find(model=>model.name===ref.name);
      return {...structuredClone(ref),displayName:summary?.displayName,description:summary?.description,tokenRateLimits:ref.tokenRateLimits ?? []};
    })};
}
export function policyDomain(cr) {
  return {...structuredClone(cr.spec),...presentation(cr)};
}
export function seedResources(namespace='maas') {
  const models=[['granite-3-8b','Granite 3.3 8B Instruct'],['llama-3-70b','Llama 3.3 70B Instruct'],['granite-research','Granite research endpoint']];
  return [
    ...models.map(([name,displayName])=>({path:`models/${namespace}/${name}.json`,resource:{apiVersion,kind:'MaaSModelRef',metadata:{name,namespace,annotations:{[displayAnnotation]:displayName}},spec:{modelRef:{kind:'LLMInferenceService',name}}}})),
  ];
}
